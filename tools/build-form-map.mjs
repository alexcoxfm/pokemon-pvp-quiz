#!/usr/bin/env node

/**
 * build-form-map.js — Regenerates js/form-map.js
 *
 * Matches every PvPoke gamemaster speciesId to a PokeAPI Pokemon entry by
 * name, so alternate forms (Galarian, Origin, Crowned, Mega, ...) get the
 * right official artwork. Only entries whose PokeAPI id differs from the
 * plain National Dex number are written; everything else falls back to the
 * gamemaster `dex` at runtime.
 *
 * Usage (Node 18+):
 *   node tools/build-form-map.js
 *
 * Re-run whenever new forms show up in Pokemon GO. It overwrites
 * js/form-map.js directly and prints any forms it couldn't match.
 */

import { writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

const GAMEMASTER_URL = 'https://raw.githubusercontent.com/pvpoke/pvpoke/master/src/data/gamemaster.json';
const POKEAPI_LIST_URL = 'https://pokeapi.co/api/v2/pokemon?limit=5000';
const ARTWORK_BASE = 'https://raw.githubusercontent.com/PokeAPI/sprites/master/sprites/pokemon/other/official-artwork';
const OUT_FILE = join(dirname(fileURLToPath(import.meta.url)), '..', 'js', 'form-map.js');

// PvPoke region words -> PokeAPI region words
const TOKEN_MAP = { alolan: 'alola', galarian: 'galar', hisuian: 'hisui', paldean: 'paldea' };

async function fetchJSON(url) {
  const res = await fetch(url);
  if (!res.ok) throw new Error(`${res.status} ${url}`);
  return res.json();
}

function candidates(cleanId) {
  const tokens = cleanId.split('_').map(t => TOKEN_MAP[t] || t);
  const full = tokens.join('-');
  const list = [full, `${full}-standard`, `${full}-breed`];
  // Progressively drop trailing words: zacian-crowned-sword -> zacian-crowned
  for (let i = tokens.length - 1; i >= 1; i--) list.push(tokens.slice(0, i).join('-'));
  return list;
}

async function artworkExists(id) {
  const res = await fetch(`${ARTWORK_BASE}/${id}.png`, { method: 'HEAD' });
  return res.ok;
}

async function main() {
  const [gamemaster, apiList] = await Promise.all([fetchJSON(GAMEMASTER_URL), fetchJSON(POKEAPI_LIST_URL)]);
  const nameToId = new Map(apiList.results.map(r => [r.name, Number(r.url.split('/').filter(Boolean).pop())]));

  const map = {};
  const unmatched = [];
  const seen = new Set();

  for (const p of gamemaster.pokemon) {
    const cleanId = p.speciesId.replace(/_shadow$/, '');
    if (seen.has(cleanId)) continue;
    seen.add(cleanId);

    const match = candidates(cleanId).find(n => nameToId.has(n));
    if (!match) {
      if (cleanId.includes('_')) unmatched.push(cleanId);
      continue;
    }
    const id = nameToId.get(match);
    if (id !== p.dex) map[cleanId] = id;
  }

  // Drop entries PokeAPI has no artwork for (they fall back to the base form)
  const missingArt = [];
  for (const [key, id] of Object.entries(map)) {
    if (!(await artworkExists(id))) {
      missingArt.push(`${key} (${id})`);
      delete map[key];
    }
  }

  const body = Object.keys(map).sort().map(k => `  '${k}': ${map[k]},`).join('\n');
  writeFileSync(OUT_FILE, `// form-map.js — GENERATED by tools/build-form-map.js. Do not edit by hand.
// PvPoke speciesId (without _shadow) -> PokeAPI Pokemon id, for forms whose
// artwork differs from the base National Dex entry.
// Generated: ${new Date().toISOString().slice(0, 10)}

export const FORM_ID_MAP = {
${body}
};
`);

  console.log(`Wrote ${Object.keys(map).length} form entries to js/form-map.js`);
  if (missingArt.length) console.log(`No artwork (using base form): ${missingArt.join(', ')}`);
  if (unmatched.length) console.log(`No PokeAPI match (using base form): ${unmatched.join(', ')}`);
}

main().catch(err => { console.error(err); process.exit(1); });
